#!/usr/bin/env node
/**
 * Writes src/lib/observability/route-templates.ts: every page and route
 * handler under src/app as a URL template ("/[locale]/inbox/[threadId]").
 * Error reports send only these templates, never concrete paths.
 *
 * Run after adding or moving a route: node scripts/generate-route-templates.mjs
 * (tests/unit/observability-routes.test.ts fails while the list is stale).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(root, "src", "app");
const outFile = path.join(root, "src", "lib", "observability", "route-templates.ts");

export function collectRouteTemplates(dir = appDir) {
  const templates = new Set();
  const walk = (current, segments) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        const name = entry.name;
        // Route groups, parallel slots and private folders don't appear in URLs.
        if (name.startsWith("_")) continue;
        const skip = /^\(.*\)$/.test(name) || name.startsWith("@");
        walk(path.join(current, name), skip ? segments : [...segments, name]);
      } else if (/^(page|route)\.(tsx?|jsx?)$/.test(entry.name)) {
        templates.add(`/${segments.join("/")}`);
      }
    }
  };
  walk(dir, []);
  return [...templates].sort();
}

export function renderRouteTemplates(templates) {
  return [
    "// Generated by scripts/generate-route-templates.mjs. Do not edit by hand.",
    "export const ROUTE_TEMPLATES: readonly string[] = [",
    ...templates.map((t) => `  ${JSON.stringify(t)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(outFile, renderRouteTemplates(collectRouteTemplates()));
  console.log(`Wrote ${path.relative(root, outFile)}`);
}
